-- 1. 创建食物表
CREATE TABLE IF NOT EXISTS foods (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  category TEXT NOT NULL,
  aliases TEXT[] DEFAULT '{}',
  calories DECIMAL(6,2) NOT NULL,
  protein DECIMAL(6,2) NOT NULL,
  fat DECIMAL(6,2) NOT NULL,
  carbs DECIMAL(6,2) NOT NULL,
  fiber DECIMAL(6,2) DEFAULT 0,
  cholesterol DECIMAL(7,2) DEFAULT 0,
  omega3 DECIMAL(8,2) DEFAULT 0,
  omega6 DECIMAL(8,2) DEFAULT 0,
  unit TEXT DEFAULT '100g',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. 启用行级安全
ALTER TABLE foods ENABLE ROW LEVEL SECURITY;

-- 3. RLS策略
-- 已登录管理员：完全控制
CREATE POLICY "admin_all_foods"
  ON foods
  FOR ALL
  TO authenticated
  USING (true)
  WITH CHECK (true);

-- 匿名用户：只能查看
CREATE POLICY "anon_select_foods"
  ON foods
  FOR SELECT
  TO anon
  USING (true);

-- 4. 触发自动更新 updated_at
CREATE OR REPLACE FUNCTION update_foods_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER foods_updated_at
  BEFORE UPDATE ON foods
  FOR EACH ROW
  EXECUTE FUNCTION update_foods_updated_at();

