-- 创建参考摄入量表
CREATE TABLE IF NOT EXISTS dietary_reference_intakes (
  id SERIAL PRIMARY KEY,
  age_group TEXT NOT NULL,          -- 人群分类（如 "18岁~", "孕妇(中)"）
  gender TEXT NOT NULL DEFAULT '通用', -- 性别: 男/女/通用/孕妇/乳母
  age_order INTEGER NOT NULL DEFAULT 99, -- 排序顺序

  -- 矿物质 (mg/d 或 μg/d)
  ca_mg REAL,      -- 钙
  p_mg REAL,       -- 磷
  k_mg REAL,       -- 钾
  na_mg REAL,      -- 钠
  mag_mg REAL,     -- 镁
  fe_mg REAL,      -- 铁
  iodine_μg REAL,  -- 碘
  zn_mg REAL,      -- 锌
  se_μg REAL,      -- 硒
  cu_mg REAL,      -- 铜
  mn_mg REAL,      -- 锰

  -- 维生素
  va_μg REAL,      -- 维生素A (μg RAE)
  vd_μg REAL,      -- 维生素D (μg)
  ve_mg REAL,      -- 维生素E (mg α-TE)
  vk_μg REAL,      -- 维生素K (μg)
  vb1_mg REAL,     -- 维生素B1 (mg)
  vb2_mg REAL,     -- 维生素B2 (mg)
  vb6_mg REAL,     -- 维生素B6 (mg)
  vb12_μg REAL,    -- 维生素B12 (μg)
  pantothenic_mg REAL, -- 泛酸 (mg)
  folate_μg REAL,  -- 叶酸 (μg DFE)
  niacin_mg REAL,  -- 烟酸 (mg NE)
  vc_mg REAL,      -- 维生素C (mg)
  biotin_μg REAL,  -- 生物素 (μg)

  -- 元数据
  source TEXT DEFAULT '中国居民膳食指南2022',
  note TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  UNIQUE(age_group, gender)
);

