/**
 * 搜索食物（支持名称和别名模糊搜索）
 * @param {string} query - 搜索关键词
 * @param {string} category - 可选，按分类筛选
 * @returns {Array} 匹配的食物列表
 */
function searchFood(query, category = null) {
  const q = query.toLowerCase().trim();
  let results = FOOD_DATABASE.filter(food => {
    // 匹配名称
    if (food.name.toLowerCase().includes(q)) return true;
    // 匹配别名
    if (food.aliases && food.aliases.some(a => a.toLowerCase().includes(q))) return true;
    return false;
  });
  
  // 按分类筛选
  if (category) {
    results = results.filter(food => food.category === category);
  }
  
  return results;
}

/**
 * 根据ID获取食物
 * @param {number} id - 食物ID
 * @returns {Object|null} 食物对象
 */
function getFoodById(id) {
  return FOOD_DATABASE.find(food => food.id === id) || null;
}

/**
 * 获取所有分类
 * @returns {Array} 分类列表
 */
function getCategories() {
  const cats = [...new Set(FOOD_DATABASE.map(f => f.category))];
  return cats.sort();
}

/**
 * 按分类获取食物
 * @param {string} category - 分类名称
 * @returns {Array} 该分类的食物列表
 */
function getFoodsByCategory(category) {
  return FOOD_DATABASE.filter(food => food.category === category);
}

/**
 * 计算吃一定量食物的营养成分
 * @param {Object} food - 食物对象
 * @param {number} grams - 摄入量（克）
 * @returns {Object} 营养成分
 */
function calcNutrition(food, grams) {
  const factor = grams / 100;
  return {
    calories: Math.round(food.per100g.calories * factor),
    protein: Math.round(food.per100g.protein * factor * 10) / 10,
    fat: Math.round(food.per100g.fat * factor * 10) / 10,
    carbs: Math.round(food.per100g.carbs * factor * 10) / 10,
    fiber: Math.round(food.per100g.fiber * factor * 10) / 10,
    cholesterol: Math.round(food.per100g.cholesterol * factor),
    omega3: Math.round(food.per100g.omega3 * factor),
    omega6: Math.round(food.per100g.omega6 * factor)
  };
}

/**
 * 计算omega3与omega6的比例
 * @param {number} omega3 - 欧米伽-3含量（mg）
 * @param {number} omega6 - 欧米伽-6含量（mg）
 * @returns {Object} 比例信息和建议
 */
function calcOmegaRatio(omega3, omega6) {
  if (omega3 === 0 || omega6 === 0) {
    return {
      ratio: null,
      ratioText: omega3 === 0 ? '无omega-3' : '无omega-6',
      status: 'warning',
      suggestion: '建议增加深海鱼或亚麻籽油摄入'
    };
  }
  
  const ratio = omega6 / omega3;
  const ratioText = `1:${Math.round(ratio * 10) / 10}`;
  
  // 夏萌建议：1:4 ~ 1:6
  let status = 'good';
  let suggestion = '比例良好';
  
  if (ratio > 6) {
    status = 'warning';
    suggestion = 'omega-6偏高，建议减少植物油，增加深海鱼或亚麻籽油';
  } else if (ratio < 4) {
    status = 'warning';
    suggestion = 'omega-3偏高，注意整体脂肪摄入量';
  }
  
  return { ratio, ratioText, status, suggestion };
}
