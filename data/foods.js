/**
 * 搜索食物（按名称/别名模糊匹配）
 */
function searchFood(query, category = null) {
  const q = query.toLowerCase().trim();
  let results = FOOD_DATABASE.filter(food => {
    if (food.name.toLowerCase().includes(q)) return true;
    if (food.aliases && food.aliases.some(a => a.toLowerCase().includes(q))) return true;
    return false;
  });
  if (category) {
    results = results.filter(food => food.category === category);
  }
  return results;
}

/**
 * 根据ID获取食物
 */
function getFoodById(id) {
  return FOOD_DATABASE.find(food => food.id === id) || null;
}

/**
 * 获取食物分类列表
 */
function getCategories() {
  const cats = [...new Set(FOOD_DATABASE.map(f => f.category))];
  return cats.sort();
}

// ==================== ω-3/ω-6 比例分析工具 ====================

function analyzeOmegaRatio(omega3, omega6) {
  if (!omega3 || !omega6 || omega3 === 0) return { ratio: null, ratioText: '未知', status: 'unknown', suggestion: '' };
  
  const ratio = omega6 / omega3;
  let status, suggestion;
  let ratioText = ratio.toFixed(2);
  
  if (ratio > 6) {
    status = 'warning';
    suggestion = 'omega-6偏高，建议减少植物油，增加深海鱼或亚麻籽油';
  } else if (ratio < 4) {
    status = 'warning';
    suggestion = 'omega-3偏高，注意整体脂肪摄入量';
  } else {
    status = 'good';
    suggestion = 'omega比例在推荐范围内';
  }
  
  return { ratio, ratioText, status, suggestion };
}
